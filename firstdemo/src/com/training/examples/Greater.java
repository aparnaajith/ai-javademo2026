package com.training.examples;

public class Greater {

	public static void main(String[] args) {
		// create three nums
		int x = 10;
		int y = 20;
		int z = 30;
		if (x > y && x > z)
			System.out.println("greater number is " + x);
		else if (y > z)
			System.out.println("greater number is " + y);
		else
			System.out.println("greater number is " + z);

	}
}
